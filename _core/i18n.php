function km_t($key)
{
    $all = km_translations();
    $lang = km_current_language();
    if (isset($all[$key][$lang])) {
        return $all[$key][$lang];
    }
    if (isset($all[$key]['en'])) {
        return $all[$key]['en'];
    }
    return $key;
}

