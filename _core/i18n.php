function km_lang_switcher_html($variant = 'header')
{
    $current = km_current_language();
    $class = $variant === 'login' ? 'km-lang-switch km-lang-switch--login' : 'km-lang-switch km-lang-switch--header';
    $html = '<nav class="' . $class . '" aria-label="' . htmlspecialchars(km_t('language'), ENT_QUOTES, 'UTF-8') . '">';
    foreach (array('so' => 'SO', 'en' => 'EN') as $code => $short) {
        $active = $current === $code ? ' is-active' : '';
        $title = $code === 'so' ? km_t('somali') : km_t('english');
        $html .= '<a class="' . $active . '" href="' . htmlspecialchars(km_language_url($code), ENT_QUOTES, 'UTF-8') . '" title="' . htmlspecialchars($title, ENT_QUOTES, 'UTF-8') . '">' . $short . '</a>';
    }
    $html .= '</nav>';
    return $html;
}
